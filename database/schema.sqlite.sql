CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name VARCHAR(60) NOT NULL,
    email VARCHAR(190) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL DEFAULT 'user',
    active INTEGER NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS news (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    title VARCHAR(200) NOT NULL,
    summary VARCHAR(400) NOT NULL,
    body TEXT NOT NULL,
    category VARCHAR(30) NOT NULL,
    image VARCHAR(255) NULL,
    author VARCHAR(80) NOT NULL DEFAULT 'Equipe Doppel',
    featured INTEGER NOT NULL DEFAULT 0,
    published_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_news_category_date ON news (category, published_at);
CREATE TABLE IF NOT EXISTS classes (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name VARCHAR(45) NOT NULL UNIQUE,
    hit_die INTEGER NOT NULL,
    primary_attr VARCHAR(3) NOT NULL,
    secondary_attr VARCHAR(3) NOT NULL,
    spell_slots INTEGER NOT NULL DEFAULT 0,
    simple_weapons INTEGER NOT NULL DEFAULT 1,
    martial_weapons INTEGER NOT NULL DEFAULT 0,
    light_armor INTEGER NOT NULL DEFAULT 0,
    medium_armor INTEGER NOT NULL DEFAULT 0,
    heavy_armor INTEGER NOT NULL DEFAULT 0,
    description TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS species (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name VARCHAR(45) NOT NULL UNIQUE,
    bonuses VARCHAR(200) NOT NULL DEFAULT '{}',
    description TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS weapons (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name VARCHAR(45) NOT NULL UNIQUE,
    damage VARCHAR(12) NOT NULL,
    category VARCHAR(10) NOT NULL,
    price INTEGER NOT NULL DEFAULT 0,
    weight REAL NOT NULL DEFAULT 0,
    properties VARCHAR(200) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS spells (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name VARCHAR(45) NOT NULL UNIQUE,
    level INTEGER NOT NULL DEFAULT 0,
    school VARCHAR(30) NOT NULL DEFAULT '',
    damage VARCHAR(12) NOT NULL DEFAULT '',
    description TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS rooms (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name VARCHAR(60) NOT NULL UNIQUE,
    description VARCHAR(400) NOT NULL DEFAULT '',
    master_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    max_players INTEGER NOT NULL DEFAULT 6,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS characters (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name VARCHAR(60) NOT NULL,
    species_id INTEGER NOT NULL REFERENCES species (id),
    class_id INTEGER NOT NULL REFERENCES classes (id),
    weapon_id INTEGER NULL REFERENCES weapons (id),
    level INTEGER NOT NULL DEFAULT 1,
    hp INTEGER NOT NULL,
    spell_slots INTEGER NOT NULL DEFAULT 0,
    attr_for INTEGER NOT NULL,
    attr_des INTEGER NOT NULL,
    attr_con INTEGER NOT NULL,
    attr_int INTEGER NOT NULL,
    attr_sab INTEGER NOT NULL,
    attr_car INTEGER NOT NULL,
    score INTEGER NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, name)
);
CREATE TABLE IF NOT EXISTS room_members (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    room_id INTEGER NOT NULL REFERENCES rooms (id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    character_id INTEGER NOT NULL REFERENCES characters (id) ON DELETE CASCADE,
    joined_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (room_id, user_id)
);
CREATE TABLE IF NOT EXISTS messages (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    room_id INTEGER NOT NULL REFERENCES rooms (id) ON DELETE CASCADE,
    user_id INTEGER NULL REFERENCES users (id) ON DELETE SET NULL,
    author VARCHAR(60) NOT NULL,
    body VARCHAR(500) NOT NULL,
    kind VARCHAR(10) NOT NULL DEFAULT 'chat',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_messages_room ON messages (room_id, id);
CREATE TABLE IF NOT EXISTS story_runs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    owner_key VARCHAR(80) NOT NULL,
    story_id VARCHAR(60) NOT NULL,
    state TEXT NOT NULL,
    finished INTEGER NOT NULL DEFAULT 0,
    ending VARCHAR(30) NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (owner_key, story_id)
);
CREATE TABLE IF NOT EXISTS sessions (
    id VARCHAR(128) PRIMARY KEY,
    data TEXT NOT NULL,
    updated_at INTEGER NOT NULL
)
