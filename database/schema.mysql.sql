CREATE TABLE IF NOT EXISTS users (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    email VARCHAR(190) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL DEFAULT 'user',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS news (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    summary VARCHAR(400) NOT NULL,
    body TEXT NOT NULL,
    category VARCHAR(30) NOT NULL,
    image VARCHAR(255) NULL,
    author VARCHAR(80) NOT NULL DEFAULT 'Equipe Doppel',
    featured TINYINT(1) NOT NULL DEFAULT 0,
    published_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_news_category_date (category, published_at)
) CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classes (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(45) NOT NULL UNIQUE,
    hit_die TINYINT UNSIGNED NOT NULL,
    primary_attr VARCHAR(3) NOT NULL,
    secondary_attr VARCHAR(3) NOT NULL,
    spell_slots TINYINT UNSIGNED NOT NULL DEFAULT 0,
    simple_weapons TINYINT(1) NOT NULL DEFAULT 1,
    martial_weapons TINYINT(1) NOT NULL DEFAULT 0,
    light_armor TINYINT(1) NOT NULL DEFAULT 0,
    medium_armor TINYINT(1) NOT NULL DEFAULT 0,
    heavy_armor TINYINT(1) NOT NULL DEFAULT 0,
    description TEXT NOT NULL
) CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS species (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(45) NOT NULL UNIQUE,
    bonuses VARCHAR(200) NOT NULL DEFAULT '{}',
    description TEXT NOT NULL
) CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS weapons (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(45) NOT NULL UNIQUE,
    damage VARCHAR(12) NOT NULL,
    category VARCHAR(10) NOT NULL,
    price INT UNSIGNED NOT NULL DEFAULT 0,
    weight DECIMAL(5, 2) NOT NULL DEFAULT 0,
    properties VARCHAR(200) NOT NULL DEFAULT ''
) CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS spells (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(45) NOT NULL UNIQUE,
    level TINYINT UNSIGNED NOT NULL DEFAULT 0,
    school VARCHAR(30) NOT NULL DEFAULT '',
    damage VARCHAR(12) NOT NULL DEFAULT '',
    description TEXT NOT NULL
) CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rooms (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(60) NOT NULL UNIQUE,
    description VARCHAR(400) NOT NULL DEFAULT '',
    master_id INT UNSIGNED NOT NULL,
    max_players TINYINT UNSIGNED NOT NULL DEFAULT 6,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (master_id) REFERENCES users (id) ON DELETE CASCADE
) CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS characters (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id INT UNSIGNED NOT NULL,
    room_id INT UNSIGNED NOT NULL,
    name VARCHAR(60) NOT NULL,
    species_id INT UNSIGNED NOT NULL,
    class_id INT UNSIGNED NOT NULL,
    weapon_id INT UNSIGNED NULL,
    level TINYINT UNSIGNED NOT NULL DEFAULT 1,
    hp SMALLINT NOT NULL,
    spell_slots TINYINT UNSIGNED NOT NULL DEFAULT 0,
    attr_for TINYINT UNSIGNED NOT NULL,
    attr_des TINYINT UNSIGNED NOT NULL,
    attr_con TINYINT UNSIGNED NOT NULL,
    attr_int TINYINT UNSIGNED NOT NULL,
    attr_sab TINYINT UNSIGNED NOT NULL,
    attr_car TINYINT UNSIGNED NOT NULL,
    score INT NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_user_room (user_id, room_id),
    UNIQUE KEY uq_room_name (room_id, name),
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE,
    FOREIGN KEY (species_id) REFERENCES species (id),
    FOREIGN KEY (class_id) REFERENCES classes (id),
    FOREIGN KEY (weapon_id) REFERENCES weapons (id)
) CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS messages (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    room_id INT UNSIGNED NOT NULL,
    user_id INT UNSIGNED NULL,
    author VARCHAR(60) NOT NULL,
    body VARCHAR(500) NOT NULL,
    kind VARCHAR(10) NOT NULL DEFAULT 'chat',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_messages_room (room_id, id),
    FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
) CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS story_runs (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    owner_key VARCHAR(80) NOT NULL,
    story_id VARCHAR(60) NOT NULL,
    state TEXT NOT NULL,
    finished TINYINT(1) NOT NULL DEFAULT 0,
    ending VARCHAR(30) NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_owner_story (owner_key, story_id)
) CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions (
    id VARCHAR(128) PRIMARY KEY,
    data TEXT NOT NULL,
    updated_at INT UNSIGNED NOT NULL
) CHARSET=utf8mb4
